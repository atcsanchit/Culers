import * as esbuild from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.join(root, '..');
const outFile = path.join(projectRoot, 'api', '[...path].js');

fs.mkdirSync(path.dirname(outFile), { recursive: true });

await esbuild.build({
	absWorkingDir: projectRoot,
	entryPoints: [path.join(projectRoot, 'scripts', 'vercel-api-entry.ts')],
	bundle: true,
	platform: 'node',
	target: 'node20',
	format: 'esm',
	outfile: outFile,
	logLevel: 'info',
	// Keep Node built-ins external; bundle all local .ts modules into one file.
	packages: 'external',
	banner: {
		js: '/* Generated by scripts/bundle-vercel-api.mjs — do not edit. */\n',
	},
});

console.log(`Bundled Vercel API → ${path.relative(projectRoot, outFile)}`);
